#!/usr/bin/env python3
"""Dual-tool training scene: a central oval tray seen from an endoscope-style
camera, with two dVRK Large Needle Drivers entering from the lower-left and
lower-right of the view.

    python3 dual_tool_gen.py

Generates:
  mesh/high_res/tray.obj            visual mesh of the tray (MuJoCo frame, metres)
  <unity>/Assets/Models/Tray/tray.obj
                                    same file for Unity (bound as a Free Body)
  mjcf/dual_tool/tray.xml           tray body: convex base + capsule rim for collision
  mjcf/dual_tool_scene.xml          tray, both tools (attached from hello_unity.xml
                                    with prefixes left_ / right_), camera, "home" key

World frame: origin = centre of the tray's floor, Z up, +Y away from the camera.
"left" / "right" are as seen from the endoscope camera; which arm drives which
tool (Justi / Gracie) is decided later in the bridge.
"""

from pathlib import Path

import numpy as np

# ---- tray (SI units) -------------------------------------------------------
TRAY_A = 0.045          # semi-axis along X (left-right in the camera view) [m]
TRAY_B = 0.030          # semi-axis along Y (depth in the camera view) [m]
TRAY_BASE_T = 0.003     # floor thickness [m]; floor top at z = 0
TRAY_RIM_R = 0.0025     # rim tube radius [m]
N_RIM = 48              # rim capsules / visual segments around the oval
N_RIM_RING = 16         # vertices per rim cross-section (visual mesh)

# ---- tools -----------------------------------------------------------------
# Jaw centre at q = 0, in the tool's own frame (measured with mj_forward on
# hello_unity.xml): the shaft runs along +X and the jaws open along Z.
TOOL_TIP_LOCAL = np.array([0.4817, 0.0, 0.0])
# Where each tool's jaws sit, and the direction its shaft points (root -> tip).
# Azimuth is measured from +Y (into the view) towards +X; elevation is downward.
TOOLS = {
    "left":  {"tip": (-0.022, 0.0, 0.012), "azimuth_deg": 28.0, "elevation_deg": 18.0},
    "right": {"tip": (0.022, 0.0, 0.012), "azimuth_deg": -28.0, "elevation_deg": 18.0},
}
JAW_HOME = 0.3  # rad, jaws slightly open at start

# ---- camera ----------------------------------------------------------------
CAM_POS = (0.0, -0.085, 0.075)
CAM_TARGET = (0.0, 0.004, 0.0)
CAM_FOVY = 55.0

GEN_DIR = Path(__file__).resolve().parent
MJCF_DIR = GEN_DIR.parent
MESH_DIR = MJCF_DIR.parent / "mesh" / "high_res"
REPO_ROOT = MJCF_DIR.parents[2]
UNITY_MESH_DIR = REPO_ROOT / "unity-sim" / "UR3-medical-robot" / "Assets" / "Models" / "Tray"

HEADER = "<!-- Generated by dual_tool_gen.py — edit the script, not this file. -->\n"


def fmt(v):
    return " ".join(f"{x:.6g}" for x in v)


def normalize(v):
    v = np.asarray(v, dtype=float)
    return v / np.linalg.norm(v)


def mat_to_quat(R):
    """Rotation matrix -> MuJoCo quaternion (w, x, y, z)."""
    w = np.sqrt(max(0.0, 1.0 + R[0, 0] + R[1, 1] + R[2, 2])) / 2.0
    x = np.copysign(np.sqrt(max(0.0, 1.0 + R[0, 0] - R[1, 1] - R[2, 2])) / 2.0, R[2, 1] - R[1, 2])
    y = np.copysign(np.sqrt(max(0.0, 1.0 - R[0, 0] + R[1, 1] - R[2, 2])) / 2.0, R[0, 2] - R[2, 0])
    z = np.copysign(np.sqrt(max(0.0, 1.0 - R[0, 0] - R[1, 1] + R[2, 2])) / 2.0, R[1, 0] - R[0, 1])
    return np.array([w, x, y, z])


# ---- tray mesh -------------------------------------------------------------
def ellipse(u, a, b):
    return np.array([a * np.cos(u), b * np.sin(u), 0.0])


def build_tray_mesh():
    """Two closed shells: an elliptic floor plate and an elliptic rim tube."""
    verts, faces = [], []

    # Floor: elliptic prism, top at z = 0.
    n = N_RIM * 2
    top_c, bot_c = len(verts), len(verts) + 1
    verts += [np.array([0.0, 0.0, 0.0]), np.array([0.0, 0.0, -TRAY_BASE_T])]
    ring0 = len(verts)
    for k in range(n):
        p = ellipse(2 * np.pi * k / n, TRAY_A, TRAY_B)
        verts += [p, p + np.array([0.0, 0.0, -TRAY_BASE_T])]
    for k in range(n):
        t0, b0 = ring0 + 2 * k, ring0 + 2 * k + 1
        t1, b1 = ring0 + 2 * ((k + 1) % n), ring0 + 2 * ((k + 1) % n) + 1
        faces += [(top_c, t0, t1), (bot_c, b1, b0), (t0, b0, b1), (t0, b1, t1)]

    # Rim: tube of radius TRAY_RIM_R swept along the ellipse, resting on the floor edge.
    rim0 = len(verts)
    m = N_RIM * 2
    for i in range(m):
        u = 2 * np.pi * i / m
        c = ellipse(u, TRAY_A, TRAY_B) + np.array([0.0, 0.0, TRAY_RIM_R])
        t = normalize([-TRAY_A * np.sin(u), TRAY_B * np.cos(u), 0.0])
        out = np.cross(t, [0.0, 0.0, 1.0])
        for j in range(N_RIM_RING):
            v = 2 * np.pi * j / N_RIM_RING
            verts.append(c + TRAY_RIM_R * (np.cos(v) * out + np.sin(v) * np.array([0.0, 0.0, 1.0])))
    for i in range(m):
        for j in range(N_RIM_RING):
            a = rim0 + i * N_RIM_RING + j
            b = rim0 + i * N_RIM_RING + (j + 1) % N_RIM_RING
            c = rim0 + ((i + 1) % m) * N_RIM_RING + (j + 1) % N_RIM_RING
            d = rim0 + ((i + 1) % m) * N_RIM_RING + j
            faces += [(a, c, b), (a, d, c)]
    return np.array(verts), np.array(faces)


def shell_volumes(verts, faces):
    v0, v1, v2 = verts[faces[:, 0]], verts[faces[:, 1]], verts[faces[:, 2]]
    vol = np.einsum("ij,ij->i", v0, np.cross(v1, v2)) / 6.0
    split = 4 * N_RIM * 2  # floor faces come first
    return vol[:split].sum(), vol[split:].sum()


def write_obj(path, verts, faces, header):
    with open(path, "w") as f:
        f.write(f"# {header}\n")
        for v in verts:
            f.write(f"v {v[0]:.9f} {v[1]:.9f} {v[2]:.9f}\n")
        for a, b, c in faces:
            f.write(f"f {a + 1} {b + 1} {c + 1}\n")


def floor_collision_obj(path):
    """Convex elliptic prism; MuJoCo hulls meshes, which is exact here."""
    n = N_RIM * 2
    verts = []
    for k in range(n):
        p = ellipse(2 * np.pi * k / n, TRAY_A, TRAY_B)
        verts += [p, p + np.array([0.0, 0.0, -TRAY_BASE_T])]
    with open(path, "w") as f:
        f.write("# dual_tool_gen.py — tray floor collision hull (vertices only)\n")
        for v in verts:
            f.write(f"v {v[0]:.9f} {v[1]:.9f} {v[2]:.9f}\n")
        # MuJoCo needs at least one face to load an OBJ; it rebuilds the hull anyway.
        f.write("f 1 3 2\n")


# ---- MJCF ------------------------------------------------------------------
def write_tray_xml(path):
    pts = [ellipse(2 * np.pi * k / N_RIM, TRAY_A, TRAY_B) + np.array([0.0, 0.0, TRAY_RIM_R])
           for k in range(N_RIM)]
    rim = "\n".join(
        f'  <geom name="tray_rim_{k}" class="tray_col" type="capsule" '
        f'fromto="{fmt(pts[k])} {fmt(pts[(k + 1) % N_RIM])}" size="{TRAY_RIM_R:g}"/>'
        for k in range(N_RIM))
    path.write_text(HEADER + f"""<!-- Static tray. Needs the tray_* assets and classes from dual_tool_scene.xml. -->
<mujoco>
<body name="tray">
  <geom name="tray_visual" class="tray_vis" mesh="tray_mesh" material="tray_mat"/>
  <geom name="tray_floor" class="tray_col" type="mesh" mesh="tray_floor_col"/>
{rim}
</body>
</mujoco>
""")


def tool_frame(spec):
    """Frame that puts the tool's jaws at spec['tip'] with its shaft along the
    given approach direction, jaws opening as close to world-up as possible."""
    az, el = np.radians(spec["azimuth_deg"]), np.radians(spec["elevation_deg"])
    x = np.array([np.cos(el) * np.sin(az), np.cos(el) * np.cos(az), -np.sin(el)])
    z = normalize(np.array([0.0, 0.0, 1.0]) - x[2] * x)
    y = np.cross(z, x)
    R = np.column_stack([x, y, z])
    pos = np.asarray(spec["tip"]) - R @ TOOL_TIP_LOCAL
    return pos, mat_to_quat(R)


def camera_xyaxes():
    fwd = normalize(np.subtract(CAM_TARGET, CAM_POS))
    right = normalize(np.cross(fwd, [0.0, 0.0, 1.0]))
    up = np.cross(right, fwd)
    return np.concatenate([right, up])


def write_scene_xml(path):
    frames = []
    for name, spec in TOOLS.items():
        pos, quat = tool_frame(spec)
        frames.append(f"""    <frame name="{name}_mount" pos="{fmt(pos)}" quat="{fmt(quat)}">
      <attach model="dvrk_tool" body="tool_main_insert_Shape_IndexedFaceSet.030" prefix="{name}_"/>
    </frame>""")
    # Per tool: roll pitch jaw_left jaw_right (attach order = TOOLS order).
    qpos = "  ".join(f"0 0 {JAW_HOME:g} {JAW_HOME:g}" for _ in TOOLS)
    path.write_text(HEADER + f"""<!-- Run: python3 mujoco_unity_bridge.py (model arg) ../mjcf/dual_tool_scene.xml
     Tools come from hello_unity.xml via <attach>, so their joints/actuators are
     prefixed: left_joint_roll, right_act_gripper_left, ... -->
<mujoco model="dual_tool_scene">
  <compiler angle="radian" meshdir="../mesh/high_res" autolimits="true"/>

  <!-- 0.5 ms leaves room for the needle/ring contacts (solref 1 ms) added later. -->
  <option timestep="0.0005" integrator="implicitfast" cone="elliptic" impratio="10" noslip_iterations="5"/>

  <visual>
    <global offwidth="1280" offheight="720"/>
    <map znear="0.001"/>
    <quality shadowsize="4096"/>
  </visual>

  <statistic center="0 0 0.01" extent="0.12"/>

  <asset>
    <model name="dvrk_tool" file="hello_unity.xml"/>
    <mesh name="tray_mesh" file="tray.obj"/>
    <mesh name="tray_floor_col" file="tray_floor_col.obj" inertia="convex"/>
    <material name="tray_mat" rgba="0.82 0.84 0.86 1" specular="0.5" shininess="0.6"/>
    <texture name="backdrop" type="2d" builtin="checker" rgb1="0.30 0.12 0.12" rgb2="0.36 0.15 0.15"
             width="256" height="256"/>
    <material name="backdrop_mat" texture="backdrop" texrepeat="8 8"/>
  </asset>

  <default>
    <default class="tray_col">
      <geom group="3" rgba="0.2 0.6 1 0.4"/>
    </default>
    <default class="tray_vis">
      <geom type="mesh" group="1" contype="0" conaffinity="0"/>
    </default>
  </default>

  <worldbody>
    <light name="key" pos="0 -0.1 0.4" dir="0 0.25 -1" directional="false" diffuse="0.8 0.8 0.8" castshadow="true"/>
    <light name="fill" pos="0 0.2 0.3" dir="0 -0.5 -1" diffuse="0.3 0.3 0.3" castshadow="false"/>
    <geom name="ground" type="plane" size="0.5 0.5 0.01" pos="0 0 {-TRAY_BASE_T:g}" material="backdrop_mat"/>

    <camera name="endoscope" pos="{fmt(CAM_POS)}" xyaxes="{fmt(camera_xyaxes())}" fovy="{CAM_FOVY:g}"/>

    <include file="dual_tool/tray.xml"/>

{chr(10).join(frames)}
  </worldbody>

  <!-- Bridge loads "home" on start and on reset.
       qpos = per tool (left, right): roll pitch jaw_left jaw_right -->
  <keyframe>
    <key name="home" qpos="{qpos}" ctrl="{qpos}"/>
  </keyframe>
</mujoco>
""")


def main():
    verts, faces = build_tray_mesh()
    vf, vr = shell_volumes(verts, faces)
    assert vf > 0 and vr > 0, f"inward-facing triangles (floor {vf}, rim {vr})"
    header = "dual_tool_gen.py — tray, MuJoCo body frame (Z-up), metres"
    outputs = [MESH_DIR / "tray.obj", MESH_DIR / "tray_floor_col.obj"]
    write_obj(outputs[0], verts, faces, header)
    floor_collision_obj(outputs[1])
    if UNITY_MESH_DIR.parent.is_dir():
        UNITY_MESH_DIR.mkdir(exist_ok=True)
        outputs.append(UNITY_MESH_DIR / "tray.obj")
        write_obj(outputs[-1], verts, faces, header)
    write_tray_xml(GEN_DIR / "tray.xml")
    write_scene_xml(MJCF_DIR / "dual_tool_scene.xml")
    outputs += [GEN_DIR / "tray.xml", MJCF_DIR / "dual_tool_scene.xml"]

    print(f"tray:   {2*TRAY_A*1e3:.0f} x {2*TRAY_B*1e3:.0f} mm, {len(verts)} vertices, {len(faces)} triangles")
    for name, spec in TOOLS.items():
        pos, _ = tool_frame(spec)
        print(f"tool {name:5s}: jaws at {fmt(np.asarray(spec['tip'])*1e3)} mm, base at {fmt(pos*1e3)} mm")
    for path in outputs:
        print(f"wrote:  {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
