#!/usr/bin/env python3
"""Dual-tool training scene: the Operation board (from operation_scene.xml) in
the centre, seen from an endoscope-style camera, with two dVRK Large Needle
Drivers entering from the lower-left and lower-right of the view.

    python3 dual_tool_gen.py

Generates:
  mjcf/dual_tool/operation_assets.xml  board + piece meshes, copied from operation_scene.xml
  mjcf/dual_tool/operation_bodies.xml  board + 12 free pieces, copied from operation_scene.xml
  mjcf/dual_tool_scene.xml             board, both tools (attached from hello_unity.xml with
                                       prefixes left_ / right_), camera, "home" keyframe

operation_scene.xml is only read, never modified: its own tool, mocap body and
weld are left out. Re-run this script after the board or pieces change there.

World frame: origin = centre of the board's footprint, Z up, +Y away from the
camera. "left" / "right" are as seen from the endoscope camera; which arm drives
which tool (Justi / Gracie) is decided later in the bridge.
"""

import copy
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco
import numpy as np

# ---- tools -----------------------------------------------------------------
# Jaw centre at q = 0, in the tool's own frame (measured with mj_forward on
# hello_unity.xml): the shaft runs along +X and the jaws open along Z.
TOOL_TIP_LOCAL = np.array([0.4817, 0.0, 0.0])
# Jaw positions relative to the board centre (x, y) and above the pieces (z),
# and the direction each shaft points (root -> tip). Azimuth is measured from
# +Y (into the view) towards +X; elevation is downward. Keep the elevation below
# the camera's so the shafts enter from the bottom corners of the view.
TOOLS = {
    "left":  {"tip": (-0.035, -0.005, 0.015), "azimuth_deg": 28.0, "elevation_deg": 20.0},
    "right": {"tip": (0.035, -0.005, 0.015), "azimuth_deg": -28.0, "elevation_deg": 20.0},
}
JAW_HOME = 0.3  # rad, jaws slightly open at start

# ---- camera (relative to the board centre, z from the board's pieces level) --
CAM_POS = (0.0, -0.15, 0.13)
CAM_TARGET = (0.0, 0.0, 0.0)
CAM_FOVY = 50.0

GEN_DIR = Path(__file__).resolve().parent
MJCF_DIR = GEN_DIR.parent
REPO_ROOT = MJCF_DIR.parents[2]
OPERATION_XML = MJCF_DIR / "operation_scene.xml"
BOARD_BODY = "operation_board_body"

HEADER = "<!-- Generated by dual_tool_gen.py from operation_scene.xml — edit the script, not this file. -->\n"


def fmt(v):
    return " ".join(f"{x:.6g}" for x in v)


def normalize(v):
    v = np.asarray(v, dtype=float)
    return v / np.linalg.norm(v)


def mat_to_quat(R):
    """Rotation matrix -> MuJoCo quaternion (w, x, y, z)."""
    w = np.sqrt(max(0.0, 1.0 + R[0, 0] + R[1, 1] + R[2, 2])) / 2.0
    x = np.copysign(np.sqrt(max(0.0, 1.0 + R[0, 0] - R[1, 1] - R[2, 2])) / 2.0, R[2, 1] - R[1, 2])
    y = np.copysign(np.sqrt(max(0.0, 1.0 - R[0, 0] + R[1, 1] - R[2, 2])) / 2.0, R[0, 2] - R[2, 0])
    z = np.copysign(np.sqrt(max(0.0, 1.0 - R[0, 0] - R[1, 1] + R[2, 2])) / 2.0, R[1, 0] - R[0, 1])
    return np.array([w, x, y, z])


# ---- Operation board -------------------------------------------------------
def extract_operation():
    """Board + pieces (top-level bodies ending in _body) and the meshes they use."""
    root = ET.parse(OPERATION_XML).getroot()
    bodies = [b for b in root.find("worldbody").findall("body") if b.get("name", "").endswith("_body")]
    used = {g.get("mesh") for b in bodies for g in b.iter("geom") if g.get("mesh")}
    meshes = [m for m in root.find("asset").findall("mesh") if m.get("name") in used]
    missing = used - {m.get("name") for m in meshes}
    assert not missing, f"meshes referenced but not defined in operation_scene.xml: {missing}"
    bodies = [copy.deepcopy(b) for b in bodies]
    # Collision geoms (convex parts, pocket floors) are semi-transparent and in the
    # default group there, so they tint the render; move them to group 3 like the
    # tool's collision geoms. Physics is unchanged.
    for b in bodies:
        for g in b.iter("geom"):
            if g.get("contype", "1") != "0" and g.get("group") is None:
                g.set("group", "3")
    return [copy.deepcopy(m) for m in meshes], bodies


def write_fragment(path, tag, elements):
    root = ET.Element("mujoco")
    parent = ET.SubElement(root, tag) if tag else root
    parent.extend(elements)
    ET.indent(root, space="  ")
    path.write_text(HEADER + ET.tostring(root, encoding="unicode") + "\n")


def measure_board():
    """Footprint centre, bottom and piece level of the board, in operation_scene.xml coords."""
    probe = MJCF_DIR / "_dual_tool_probe.xml"
    probe.write_text(f"""<mujoco><compiler meshdir="../mesh/high_res"/>
  <include file="dual_tool/operation_assets.xml"/>
  <worldbody><include file="dual_tool/operation_bodies.xml"/></worldbody></mujoco>""")
    try:
        m = mujoco.MjModel.from_xml_path(str(probe))
    finally:
        probe.unlink()
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)

    def aabb(body):
        pts = []
        for g in range(m.ngeom):
            if m.geom_bodyid[g] != body:
                continue
            R, c = d.geom_xmat[g].reshape(3, 3), d.geom_xpos[g]
            if m.geom_type[g] == mujoco.mjtGeom.mjGEOM_MESH:
                k = m.geom_dataid[g]
                pts.append(m.mesh_vert[m.mesh_vertadr[k]:m.mesh_vertadr[k] + m.mesh_vertnum[k]] @ R.T + c)
            else:
                pts.append(c + np.outer([1, -1], m.geom_size[g][:3]) @ R.T)
        pts = np.vstack(pts)
        return pts.min(0), pts.max(0)

    board = m.body(BOARD_BODY).id
    lo, hi = aabb(board)
    piece_tops = [aabb(b)[1][2] for b in range(1, m.nbody) if b != board and m.body_parentid[b] == 0]
    return np.array([(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2]), lo[2], float(np.median(piece_tops)), hi - lo


# ---- tools and camera ------------------------------------------------------
def tool_frame(tip, spec):
    """Frame that puts the tool's jaws at `tip` with its shaft along the given
    approach direction, jaws opening as close to world-up as possible."""
    az, el = np.radians(spec["azimuth_deg"]), np.radians(spec["elevation_deg"])
    x = np.array([np.cos(el) * np.sin(az), np.cos(el) * np.cos(az), -np.sin(el)])
    z = normalize(np.array([0.0, 0.0, 1.0]) - x[2] * x)
    y = np.cross(z, x)
    R = np.column_stack([x, y, z])
    return np.asarray(tip) - R @ TOOL_TIP_LOCAL, mat_to_quat(R)


def camera_xyaxes(pos, target):
    fwd = normalize(np.subtract(target, pos))
    right = normalize(np.cross(fwd, [0.0, 0.0, 1.0]))
    return np.concatenate([right, np.cross(right, fwd)])


def write_scene_xml(path, centre_xy, bottom_z, level_z):
    level = np.array([0.0, 0.0, level_z])
    frames = []
    for name, spec in TOOLS.items():
        pos, quat = tool_frame(level + spec["tip"], spec)
        frames.append(f"""    <frame name="{name}_mount" pos="{fmt(pos)}" quat="{fmt(quat)}">
      <attach model="dvrk_tool" body="tool_main_insert_Shape_IndexedFaceSet.030" prefix="{name}_"/>
    </frame>""")
    cam_pos, cam_target = level + CAM_POS, level + CAM_TARGET
    # Per tool: roll pitch jaw_left jaw_right (attach order = TOOLS order); the
    # 12 free pieces keep their qpos0 (the "home" key lists the full qpos below).
    tools_q = "  ".join(f"0 0 {JAW_HOME:g} {JAW_HOME:g}" for _ in TOOLS)
    path.write_text(HEADER + f"""<!-- Run: python3 mujoco_unity_bridge.py (model arg) ../mjcf/dual_tool_scene.xml
     Tools come from hello_unity.xml via <attach>, so their joints/actuators are
     prefixed: left_joint_roll, right_act_gripper_left, ... -->
<mujoco model="dual_tool_scene">
  <compiler angle="radian" meshdir="../mesh/high_res" autolimits="true"/>

  <!-- Same as operation_scene.xml: 0.5 ms, Newton; plus elliptic cones and noslip for grasping. -->
  <option timestep="0.0005" solver="Newton" iterations="100" tolerance="1e-10"
          integrator="implicitfast" cone="elliptic" impratio="10" noslip_iterations="5"/>

  <visual>
    <global offwidth="1280" offheight="720"/>
    <map znear="0.001"/>
    <quality shadowsize="4096"/>
  </visual>

  <statistic center="{fmt(level)}" extent="0.25"/>

  <asset>
    <model name="dvrk_tool" file="hello_unity.xml"/>
    <texture name="backdrop" type="2d" builtin="checker" rgb1="0.30 0.12 0.12" rgb2="0.36 0.15 0.15"
             width="256" height="256"/>
    <material name="backdrop_mat" texture="backdrop" texrepeat="8 8"/>
  </asset>
  <include file="dual_tool/operation_assets.xml"/>

  <worldbody>
    <light name="key" pos="0 -0.15 0.5" dir="0 0.3 -1" diffuse="0.8 0.8 0.8" castshadow="true"/>
    <light name="fill" pos="0 0.3 0.4" dir="0 -0.6 -1" diffuse="0.3 0.3 0.3" castshadow="false"/>
    <geom name="ground" type="plane" size="0.6 0.6 0.01" pos="0 0 {bottom_z:.6g}" material="backdrop_mat"/>

    <camera name="endoscope" pos="{fmt(cam_pos)}" xyaxes="{fmt(camera_xyaxes(cam_pos, cam_target))}" fovy="{CAM_FOVY:g}"/>

    <!-- Board centred on the origin; operation_scene.xml places it at {fmt(centre_xy)}. -->
    <frame name="operation_mount" pos="{fmt([-centre_xy[0], -centre_xy[1], 0.0])}">
      <include file="dual_tool/operation_bodies.xml"/>
    </frame>

{chr(10).join(frames)}
  </worldbody>
</mujoco>
""")
    return tools_q


def add_home_key(path, tools_q):
    """"home" needs the full qpos: the free pieces' qpos0 come first (bodies before
    the tools in the tree), so read them from the compiled model."""
    m = mujoco.MjModel.from_xml_path(str(path))
    n_tool = 4 * len(TOOLS)
    pieces_q = fmt(m.qpos0[:m.nq - n_tool])
    text = path.read_text().replace("</mujoco>\n", f"""
  <!-- Bridge loads "home" on start and on reset.
       qpos = 12 free pieces (as placed in operation_scene.xml) | per tool (left, right): roll pitch jaw_left jaw_right -->
  <keyframe>
    <key name="home" qpos="{pieces_q}  {tools_q}" ctrl="{tools_q}"/>
  </keyframe>
</mujoco>
""")
    path.write_text(text)


def main():
    meshes, bodies = extract_operation()
    write_fragment(GEN_DIR / "operation_assets.xml", "asset", meshes)
    write_fragment(GEN_DIR / "operation_bodies.xml", None, bodies)
    centre_xy, bottom_z, level_z, size = measure_board()
    scene = MJCF_DIR / "dual_tool_scene.xml"
    tools_q = write_scene_xml(scene, centre_xy, bottom_z, level_z)
    add_home_key(scene, tools_q)

    print(f"board:  {size[0]*1e3:.0f} x {size[1]*1e3:.0f} mm, {len(bodies) - 1} pieces, "
          f"pieces level z = {level_z*1e3:.1f} mm, ground z = {bottom_z*1e3:.1f} mm")
    for name, spec in TOOLS.items():
        print(f"tool {name:5s}: jaws at {fmt(np.add(spec['tip'], [0, 0, level_z]) * 1e3)} mm")
    for p in [GEN_DIR / "operation_assets.xml", GEN_DIR / "operation_bodies.xml", scene]:
        print(f"wrote:  {p.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
