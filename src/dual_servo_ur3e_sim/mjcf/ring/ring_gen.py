#!/usr/bin/env python3
"""Procedural ring (torus): one source of truth for MuJoCo and Unity.

    python3 ring_gen.py                    # defaults below
    python3 ring_gen.py --radius 6         # central (major) radius in mm
    python3 ring_gen.py --radius 6 --tube 1

Generates:
  mesh/high_res/ring.obj        visual mesh in MuJoCo frame (Z-up, metres), next
                                to the tool meshes so it shares their meshdir
  <unity>/Assets/Models/Ring/ring.obj
                                same file for Unity; MujocoBridge.cs rotates it
                                like the tool meshes (MuJoCo (x,y,z) -> Unity (x,z,y))
  mjcf/ring/ring_assets.xml     mesh, material and geom classes; include at top level
  mjcf/ring/ring_body.xml       ring body at the origin; include inside a <frame>
  mjcf/ring_drop.xml            table + ring dropped from a few cm, for mujoco.viewer
  mjcf/ring_grasp.xml           dVRK tool + ring on a stand with its near edge
                                between the jaws; regenerated because the ring and
                                stand placement depend on the radius

Ring frame (body "ring"):
  origin  = centre of the ring
  plane   = local XY; the tube's centreline is the circle of radius RADIUS
"""

import argparse
from pathlib import Path

import numpy as np

# ---- ring geometry (SI units) ---------------------------------------------
RADIUS = 0.005        # central (major) radius: centre of ring -> centre of tube [m]
TUBE_RADIUS = 0.00075  # cross-section radius [m]; 1.5 mm thick fits the jaw gap
DENSITY = 1240.0      # PLA / rigid plastic [kg/m^3]

# ---- discretisation --------------------------------------------------------
N_MAJOR = 96     # rings around the major circle (visual mesh)
N_MINOR = 24     # vertices per cross-section (visual mesh)
N_CAPSULES = 24  # collision capsules around the major circle

# ---- scenes ----------------------------------------------------------------
DROP_HEIGHT = 0.03  # [m] above the table top

# dVRK jaws (hello_unity.xml, measured with mj_forward): they open/close along
# world Z, centred on z = 0, and span x = 479..484.5 mm at y = 0.
JAW_GRASP_X = 0.4825     # where the ring's near edge sits between the jaws [m]
JAW_TIP_X = 0.4845       # jaw tips; the stand starts past them
STAND_CLEARANCE = 0.0003  # gap between the jaw tips and the stand [m]
FLOOR_Z = -0.02          # hello_unity.xml floor plane

RING_DIR = Path(__file__).resolve().parent
MJCF_DIR = RING_DIR.parent
MESH_DIR = MJCF_DIR.parent / "mesh" / "high_res"
REPO_ROOT = MJCF_DIR.parents[2]
UNITY_MESH_DIR = REPO_ROOT / "unity-sim" / "UR3-medical-robot" / "Assets" / "Models" / "Ring"

HEADER = "<!-- Generated by ring_gen.py — edit the script, not this file. -->\n"


def fmt(v):
    return " ".join(f"{x:.6g}" for x in v)


# ---- visual mesh -----------------------------------------------------------
def build_mesh(R, r):
    """Torus: a circle of radius r swept around the major circle of radius R."""
    verts, faces = [], []
    for i in range(N_MAJOR):
        u = 2.0 * np.pi * i / N_MAJOR
        radial = np.array([np.cos(u), np.sin(u), 0.0])
        for j in range(N_MINOR):
            v = 2.0 * np.pi * j / N_MINOR
            verts.append((R + r * np.cos(v)) * radial + np.array([0.0, 0.0, r * np.sin(v)]))

    # Closed in both directions; wound so normals point outwards (signed volume > 0).
    for i in range(N_MAJOR):
        for j in range(N_MINOR):
            a = i * N_MINOR + j
            b = i * N_MINOR + (j + 1) % N_MINOR
            c = ((i + 1) % N_MAJOR) * N_MINOR + (j + 1) % N_MINOR
            d = ((i + 1) % N_MAJOR) * N_MINOR + j
            faces.append((a, d, c))
            faces.append((a, c, b))
    return np.array(verts), np.array(faces)


def signed_volume(verts, faces):
    v0, v1, v2 = verts[faces[:, 0]], verts[faces[:, 1]], verts[faces[:, 2]]
    return float(np.einsum("ij,ij->i", v0, np.cross(v1, v2)).sum() / 6.0)


def write_obj(path, verts, faces, header):
    with open(path, "w") as f:
        f.write(f"# {header}\n")
        for v in verts:
            f.write(f"v {v[0]:.9f} {v[1]:.9f} {v[2]:.9f}\n")
        for a, b, c in faces:
            f.write(f"f {a + 1} {b + 1} {c + 1}\n")


# ---- collision capsules ----------------------------------------------------
def capsule_segments(R):
    """Chords of the major circle. A torus mesh would be convex-hulled into a
    solid disc, so collision is a closed chain of capsules around the ring."""
    pts = [np.array([R * np.cos(u), R * np.sin(u), 0.0])
           for u in 2.0 * np.pi * np.arange(N_CAPSULES) / N_CAPSULES]
    return [(pts[k], pts[(k + 1) % N_CAPSULES]) for k in range(N_CAPSULES)]


# ---- MJCF ------------------------------------------------------------------
def write_ring_assets(path):
    # Same contact tuning as the needle (see needle_gen.py): sub-mm solimp width,
    # 1 ms solref, solmix so the ring's values win over the jaws'/table's defaults.
    path.write_text(HEADER + f"""<mujoco>
  <asset>
    <mesh name="ring_mesh" file="ring.obj"/>
    <material name="ring_plastic" rgba="0.95 0.55 0.10 1" specular="0.3" shininess="0.4"/>
  </asset>

  <default>
    <default class="ring_col">
      <!-- Collision only: invisible (group 3). Mass comes from the body's
           <inertial>. solref time constant must stay >= 2 * timestep. -->
      <geom type="capsule" group="3" rgba="1 0.3 0.1 0.5"
            condim="4" friction="0.8 0.02 0.0001"
            solref="0.001 1" solimp="0.99 0.999 0.0001" solmix="1000"/>
    </default>
    <default class="ring_vis">
      <!-- Visual only: no collisions, no mass. -->
      <geom type="mesh" group="1" contype="0" conaffinity="0" density="0"/>
    </default>
  </default>
</mujoco>
""")


def torus_inertia(R, r):
    """Exact mass and principal inertia of a solid torus (axis = local Z)."""
    m = DENSITY * 2.0 * np.pi**2 * R * r**2
    i_axis = m * (R**2 + 0.75 * r**2)
    i_diam = m * (0.5 * R**2 + 0.625 * r**2)
    return m, np.array([i_diam, i_diam, i_axis])


def write_ring_body(path, R, r):
    mass, inertia = torus_inertia(R, r)
    caps = "\n".join(
        f'  <geom name="ring_col_{k}" class="ring_col" fromto="{fmt(p0)} {fmt(p1)}" size="{r:.6g}"/>'
        for k, (p0, p1) in enumerate(capsule_segments(R))
    )
    path.write_text(HEADER + f"""<!-- Needs ring_assets.xml included at the top level of the scene.
     Central radius {R*1e3:g} mm, tube radius {r*1e3:g} mm. -->
<mujoco>
<body name="ring">
  <freejoint name="ring_free"/>
  <!-- Explicit, because the capsules' end caps overlap at every joint of the
       chain and MuJoCo would count that volume twice (~75 % extra mass at R = 5 mm). -->
  <inertial pos="0 0 0" mass="{mass:.6g}" diaginertia="{fmt(inertia)}"/>
  <geom name="ring_visual" class="ring_vis" mesh="ring_mesh" material="ring_plastic"/>
{caps}
</body>
</mujoco>
""")


def write_drop_scene(path, R):
    path.write_text(HEADER + f"""<mujoco model="ring_drop">
  <compiler angle="degree" meshdir="../mesh/high_res"/>

  <option timestep="0.0005" integrator="implicitfast" cone="elliptic" impratio="10"/>

  <visual>
    <global offwidth="1280" offheight="720"/>
    <map znear="0.001"/>
  </visual>

  <statistic center="0 0 0.01" extent="{max(0.05, 6 * R):g}"/>

  <include file="ring/ring_assets.xml"/>

  <worldbody>
    <light pos="0 0 0.5" dir="0 0 -1" directional="true"/>
    <geom name="table" type="box" size="0.1 0.1 0.005" pos="0 0 -0.005" rgba="0.2 0.4 0.3 1"/>
    <frame pos="0 0 {DROP_HEIGHT:g}" euler="20 10 0">
      <include file="ring/ring_body.xml"/>
    </frame>
  </worldbody>
</mujoco>
""")


def grasp_layout(R, r):
    """Ring lying flat at z = 0 with its near edge (-x side) between the jaws;
    a stand under the rest of the ring, starting just past the jaw tips."""
    centre = np.array([JAW_GRASP_X + R, 0.0, 0.0])
    x0 = JAW_TIP_X + STAND_CLEARANCE
    x1 = centre[0] + R + r + 0.003
    half_y = R + r + 0.003
    top = -r  # ring rests on it, tube centred in the jaw gap
    stand_pos = np.array([(x0 + x1) / 2, 0.0, (top + FLOOR_Z) / 2])
    stand_size = np.array([(x1 - x0) / 2, half_y, (top - FLOOR_Z) / 2])
    # Overhang check: the ring's centre of mass (its centre) must be over the stand.
    assert centre[0] > x0, "ring centre would hang off the stand; increase --radius"
    return centre, stand_pos, stand_size


def write_grasp_scene(path, R, r):
    centre, stand_pos, stand_size = grasp_layout(R, r)
    qpos_ring = f"{fmt(centre)} 1 0 0 0"
    path.write_text(HEADER + f"""<!-- dVRK Large Needle Driver + ring (central radius {R*1e3:g} mm) on a stand.
     Run: python3 mujoco_unity_bridge.py (model arg) ../mjcf/ring_grasp.xml
     Jaws open/close along world Z around x = 482 mm; the ring lies flat at z = 0
     with its near edge overhanging the stand into the jaw gap. -->
<mujoco model="ring_grasp">
  <include file="hello_unity.xml"/>
  <include file="ring/ring_assets.xml"/>

  <!-- Overrides hello_unity.xml: the ring's contact solref (1 ms) needs
       timestep <= 0.5 ms; elliptic cones + impratio + noslip keep the grasp from creeping. -->
  <option timestep="0.0005" integrator="implicitfast" cone="elliptic" impratio="10" noslip_iterations="5"/>

  <visual>
    <map znear="0.001"/>
  </visual>

  <worldbody>
    <!-- Starts past the jaw tips so the jaws never hit it; top at z = -tube radius. -->
    <geom name="ring_stand" type="box" pos="{fmt(stand_pos)}" size="{fmt(stand_size)}"
          rgba="0.25 0.45 0.55 1"/>

    <frame pos="{fmt(centre)}">
      <include file="ring/ring_body.xml"/>
    </frame>
  </worldbody>

  <!-- Bridge loads "home" on start and on reset: jaws open around the ring's edge.
       qpos = roll pitch jaw_left jaw_right | ring x y z qw qx qy qz -->
  <keyframe>
    <key name="home" qpos="0 0 0.5 0.5  {qpos_ring}" ctrl="0 0 0.5 0.5"/>
  </keyframe>
</mujoco>
""")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--radius", type=float, default=RADIUS * 1e3,
                    help=f"central (major) radius in mm (default {RADIUS*1e3:g})")
    ap.add_argument("--tube", type=float, default=TUBE_RADIUS * 1e3,
                    help=f"tube (cross-section) radius in mm (default {TUBE_RADIUS*1e3:g})")
    args = ap.parse_args()
    R, r = args.radius * 1e-3, args.tube * 1e-3
    if r >= R:
        ap.error("--tube must be smaller than --radius")

    verts, faces = build_mesh(R, r)
    assert signed_volume(verts, faces) > 0, "inward-facing triangles"
    header = f"ring_gen.py — R={args.radius:g} mm r={args.tube:g} mm, MuJoCo body frame (Z-up), metres"
    outputs = [MESH_DIR / "ring.obj"]
    write_obj(outputs[0], verts, faces, header)
    if UNITY_MESH_DIR.parent.is_dir():
        UNITY_MESH_DIR.mkdir(exist_ok=True)
        outputs.append(UNITY_MESH_DIR / "ring.obj")
        write_obj(outputs[-1], verts, faces, header)
    write_ring_assets(RING_DIR / "ring_assets.xml")
    write_ring_body(RING_DIR / "ring_body.xml", R, r)
    write_drop_scene(MJCF_DIR / "ring_drop.xml", R)
    write_grasp_scene(MJCF_DIR / "ring_grasp.xml", R, r)
    outputs += [RING_DIR / "ring_assets.xml", RING_DIR / "ring_body.xml",
                MJCF_DIR / "ring_drop.xml", MJCF_DIR / "ring_grasp.xml"]

    mass, _ = torus_inertia(R, r)
    print(f"ring:   R={args.radius:g} mm, tube r={args.tube:g} mm, "
          f"outer diameter {2*(R+r)*1e3:.2f} mm, ~{mass*1e6:.1f} mg")
    print(f"mesh:   {len(verts)} vertices, {len(faces)} triangles")
    for path in outputs:
        print(f"wrote:  {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
